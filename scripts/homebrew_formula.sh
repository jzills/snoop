#!/usr/bin/env bash
# Print the Homebrew formula for a release, from the archives
# scripts/build_binaries.sh produced. The release workflow commits the output
# to the tap repo (jzills/homebrew-tap) as Formula/snoop.rb, so
#
#   brew install jzills/tap/snoop
#
# installs the prebuilt binary for the user's platform.
#
#   scripts/homebrew_formula.sh <version> [dist]
set -euo pipefail

version="${1:?usage: homebrew_formula.sh <version> [dist]}"
version="${version#v}"
dist="${2:-dist}"
repo="https://github.com/jzills/snoop"

sha() {
  local f="$dist/snoop_v${version}_$1.tar.gz"
  test -f "$f" || { echo "missing $f" >&2; exit 1; }
  sha256sum "$f" | cut -d' ' -f1
}

url() { echo "$repo/releases/download/v${version}/snoop_v${version}_$1.tar.gz"; }

cat <<RUBY
# Generated by scripts/homebrew_formula.sh for v${version}; do not edit by hand.
class Snoop < Formula
  desc "Terminal viewer for Claude Code session transcripts"
  homepage "${repo}"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "$(url darwin_arm64)"
      sha256 "$(sha darwin_arm64)"
    end
    on_intel do
      url "$(url darwin_amd64)"
      sha256 "$(sha darwin_amd64)"
    end
  end

  on_linux do
    on_arm do
      url "$(url linux_arm64)"
      sha256 "$(sha linux_arm64)"
    end
    on_intel do
      url "$(url linux_amd64)"
      sha256 "$(sha linux_amd64)"
    end
  end

  def install
    bin.install "snoop"
  end

  test do
    assert_match "snoop v#{version}", shell_output("#{bin}/snoop --version")
  end
end
RUBY
